#ifndef _OTHER_SOCK_STREAM_H_
#define _OTHER_SOCK_STREAM_H_


#include "Socket.h"


namespace other::net::sockets
{
    /**
     * @brief Класс-обёртка для работы с сетевым сокетом через концепцию потока (Stream).
     *
     * @details
     * ### Что это такое и зачем нужно? (Руководство для новичка)
     * Представьте, что вы хотите отправить письмо или пообщаться по телефону.
     * Обычный сетевой сокет (`Socket`) из операционной системы — это просто «труба»,
     * в которую можно бросать сырые байты. Работать с ним напрямую **очень неудобно**:
     * нужно вручную следить за кусочками данных, делить текст и постоянно думать о байтах.
     *
     * Класс **`StreamSocket`** — это удобная «обёртка»-переводчик. Он превращает сложный
     * сокет в привычный **поток ввода-вывода** (точно так же, как работа с файлами или консолью).
     *
     * ### Главные возможности класса:
     * 1. **Пиши и читай как в консоли:** Используйте привычные знаки `<<` и `>>`
     *    (например: `socket << "Hello";` или `socket >> myNumber;`).
     * 2. **Защита от «обрывов» (TCP-фрагментации):** Такие методы, как `WriteAll` и `ReadExactly`,
     *    автоматически крутятся в циклах, пока весь пакет данных не уйдёт или не соберётся целиком.
     * 3. **Защита от мусора и падений:** Если вы ждёте число, а по сети прилетит словесный мусор (буквы),
     *    программа **не упадёт** благодаря встроенной защите (`try-catch`), а переменная останется в безопасности.
     * 4. **Форматирование:** Метод `WriteFormat` позволяет отправлять строки с переменными на лету (в стиле `printf`),
     *    а шаблонный `ReadFormat` автоматически разбирает входящую строку по переменным.
     * 5. **Безопасность ресурсов (RAII):** Сокет автоматически закроется и освободит память компьютера,
     *    когда объект станет больше не нужен.
     */
    class StreamSocket
    {
    private:
        Socket _socket; ///< Базовый низкоуровневый сетевой сокет, спрятанный внутри.

    public:
        /**
         * @brief Конструктор. Создает потоковый сокет на базе существующего объекта Socket.
         * @param socket Ссылка на объект `Socket` (перемещается внутрь с помощью std::move).
         */
        explicit StreamSocket(Socket& socket);
        /**
         * @brief Деструктор. Автоматически закрывает соединение и освобождает ресурсы.
         */
        ~StreamSocket();

        // Запрещаем копирование, чтобы два объекта случайно не управляли одним и тем же сокетом.
        StreamSocket(const StreamSocket&) = delete;
        StreamSocket& operator=(const StreamSocket&) = delete;

        // Разрешаем перемещение (безопасную передачу владения сокетом от одного объекта к другому).
        StreamSocket(StreamSocket&& other) noexcept = default;
        StreamSocket& operator=(StreamSocket&& other) noexcept = default;
        /**
         * @brief Возвращает текущий таймаут операции записи в миллисекундах.
         * @details Запрашивает у базового сокета время ожидания отправки данных (Send).
         * @return Значение таймаута в миллисекундах, либо -1 в случае ошибки.
         */
        int GetWriteTimeout() const;
        /**
         * @brief Устанавливает таймаут операции записи в миллисекундах.
         * @details Ограничивает время, в течение которого система будет пытаться отправить данные в сеть.
         * @param timeout Время ожидания в мс (0 или отрицательное число — ждать бесконечно).
         * @return Успешно установленное значение таймаута или -1 при ошибке.
         */
        int SetWriteTimeout(int timeout);
        /**
         * @brief Возвращает текущий таймаут операции чтения в миллисекундах.
         * @details Запрашивает у базового сокета время ожидания входящих данных (Recv).
         * @return Значение таймаута в мс, либо -1, если чтение невозможно.
         */
        int GetReadTimeout() const;
        /**
         * @brief Устанавливает таймаут операции чтения в миллисекундах.
         * @details Задает максимальное время ожидания ответа от удаленной стороны.
         *          Если данные не придут вовремя, операция чтения прервется.
         * @param timeout Время ожидания в мс.
         * @return Установленное значение таймаута или -1 при ошибке.
         */
        int SetReadTimeout(int timeout);
        /**
         * @brief Проверяет, поддерживает ли поток таймауты.
         * @return Всегда true, так как сетевые сокеты позволяют настраивать задержки.
         */
        bool CanTimeout() const;
        /**
         * @brief Проверяет, готов ли поток к записи данных.
         * @return true, если соединение активно; иначе false.
         */
        bool CanWrite() const;
        /**
         * @brief Проверяет, поддерживает ли поток произвольный поиск (перемещение курсора назад/вперед).
         * @return Всегда false, так как сеть — это непрерывный поток байтов ("труба"), нельзя вернуться к уже прочитанному.
         */
        bool CanSeek() const;
        /**
         * @brief Проверяет, готов ли поток к чтению данных.
         * @return true, если сокет создан и успешно соединен с сервером/клиентом; иначе false.
         */
        bool CanRead() const;
        /**
         * @brief Предоставляет прямой доступ к внутреннему объекту Socket.
         * @warning **Использовать с осторожностью!** Вмешательство в обход класса может нарушить логику.
         * @return Ссылка на базовый объект `Socket`.
         */
        Socket& SockInternal();
        const Socket& SockInternal() const;
        /**
         * @brief Записывает порцию байт в сетевой сокет.
         * @param [in] buffer Указатель на массив байт.
         * @param [in] size Количество байт для отправки.
         * @return Количество фактически отправленных байт, либо -1 в случае ошибки.
         */
        int Write(const char* buffer, int size);
        /**
         * @brief Записывает стандартный вектор байт (`std::vector<char>`) в поток.
         * @param [in] data Вектор с данными.
         * @return Количество фактически отправленных байт, либо -1 в случае ошибки.
         */
        int Write(const std::vector<char>& data);
        /**
         * @brief Записывает текстовую строку в поток.
         * @param [in] text Строка для отправки (`std::string`).
         * @return Количество фактически отправленных байт, либо -1 в случае ошибки.
         */
        int WriteString(const std::string& text);
        /**
         * @brief Гарантированно отправляет все `size` байт.
         * @details Так как TCP может отправлять данные частями, этот метод крутится в цикле,
         *          пока не отправит весь буфер до последнего байта.
         * @param [in] buffer Указатель на массив байт.
         * @param [in] size Общий размер данных.
         * @return true, если ушло абсолютно всё; false при разрыве соединения.
         */
        bool WriteAll(const char* buffer, int size);
        /**
         * @brief Считывает доступные данные из потока в буфер.
         * @param [out] buffer Куда складывать принятые байты.
         * @param [in] size Максимальный размер буфера.
         * @return Количество прочитанных байт, 0 если соединение закрыто, или -1 при ошибке.
         */
        int Read(char* buffer, int size);
        /**
         * @brief Гарантированно вычитывает ровно `size` байт.
         * @details Блокирует выполнение программы до тех пор, пока не соберет пакет целиком.
         * @param [out] buffer Куда складывать данные.
         * @param [in] size Сколько ровно байт нужно получить.
         * @return true, если собрали ровно столько, сколько просили; иначе false.
         */
        bool ReadExactly(char* buffer, int size);
        /**
         * @brief Читает ровно `size` байт и упаковывает их в новый вектор.
         * @param [in] size Количество байт.
         * @return `std::vector<char>` с данными (пустой в случае сбоя).
         */
        std::vector<char> ReadBytes(int size);
        /**
         * @brief Читает блок данных указанной длины и возвращает его как строку.
         * @param [in] size Количество байт.
         * @return Строка с прочитанными данными.
         */
        std::string ReadString(int size);
        /**
         * @brief Построчное чтение данных из потока (читает до символа '\n').
         * @details Удобно для текстовых протоколов. Символы возврата каретки (`\r`) автоматически отбрасываются.
         * @param [in] delimiter Символ конца строки (по умолчанию перевод строки '\n').
         * @return Прочитанная строка без учета разделителя.
         */
        std::string ReadLine(char delimiter = '\n');
        /**
         * @brief Читает данные из потока до тех пор, пока не встретит заданный маркер-разделитель.
         * @details Удобно для чтения составных протоколов (например, заголовков HTTP до "\r\n\r\n").
         * @param [in] delimiter Строка-разделитель (например, "\r\n").
         * @return Прочитанная строка (сам разделитель удаляется из конца и не возвращается).
         */
        std::string ReadUntil(const std::string& delimiter);
        /**
         * @brief Возвращает количество байт, которые уже скачались и ждут в буфере на чтение.
         * @return Количество байт или -1 при сбое.
         */
        int Available() const;
        /**
         * @brief Принудительно очищает буферы (заглушка).
         * @details В TCP пакеты улетают сразу, поэтому здесь метод пустой, создан для совместимости со стандартными потоками.
         */
        void Flush();
        /**
         * @brief Штатно закрывает соединение с заданным таймаутом.
         * @param [in] timeout Время ожидания в мс.
         * @return true в случае успеха.
         */
        bool Close(int timeout);
        /**
         * @brief Экстренно разрушает сокет и освобождает системные ресурсы.
         * @return true в случае успеха.
         */
        bool Dispose();
        /**
         * @brief Проверяет, появились ли данные для чтения, в течение заданного времени.
         * @details Позволяет не зависать намертво при чтении, если сеть молчит.
         * @param [in] timeoutMs Время ожидания в миллисекундах.
         * @return true, если данные есть и можно читать; false по истечении времени.
         */
        bool WaitForData(int timeoutMs) const;
        /**
         * @brief Записывает в поток отформатированную строку (в стиле printf).
         * @param [in] format Строка форматирования (например, "USER %s %d\r\n").
         * @param [in] ... Аргументы для форматирования.
         * @return Количество отправленных байт либо -1 в случае ошибки.
         */
        int WriteFormat(const char* format, ...);
        /**
         * @brief Считывает строку из потока и разбирает её на несколько переменных.
         * @details Использует потоковые операторы >>, поэтому полностью безопасен и защищен от мусора.
         * @param [out] args Ссылки на переменные, в которые запишется результат.
         * @return true, если всё успешно прочиталось и распарсилось; иначе false.
         */
        template<typename... Args>
        bool ReadFormat(Args&... args)
        {
            // Читаем строку до символа перевода строки
            std::string line = ReadLine('\n');
            if (line.empty())
            {
                return false;
            }

            // Создаем строковый поток для разбора
            std::istringstream iss(line);

            // Последовательно применяем оператор >> к каждому аргументу (C++17 Fold Expression)
            // Если хотя бы одно поле не распарсится — вернется false
            return ((iss >> args) && ...);
        }

        //////////////////////////////////////////////
        ///     ПОТОКОВЫЕ ОПЕРАТОРЫ ЗАПИСИ (<<)    ///
        //////////////////////////////////////////////
        StreamSocket& operator<<(const std::string& text);
        StreamSocket& operator<<(const char* text);
        StreamSocket& operator<<(bool value);
        StreamSocket& operator<<(char value);
        StreamSocket& operator<<(int8_t value);
        StreamSocket& operator<<(int16_t value);
        StreamSocket& operator<<(int32_t value);
        StreamSocket& operator<<(int64_t value);
        StreamSocket& operator<<(uint8_t value);
        StreamSocket& operator<<(uint16_t value);
        StreamSocket& operator<<(uint32_t value);
        StreamSocket& operator<<(uint64_t value);
        StreamSocket& operator<<(float value);
        StreamSocket& operator<<(double value);

        //////////////////////////////////////////////
        ///     ПОТОКОВЫЕ ОПЕРАТОРЫ ЧТЕНИЯ (>>)    ///
        //////////////////////////////////////////////
        /**
         * @note **Безопасность при чтении чисел и строк:**
         *       Все операторы ниже читают строку до символа `\n` и пытаются превратить её в число.
         *       * **Если по сети прилетит мусор** (например, вместо числа пришлют буквы `"abc"`),
         *         сработает встроенная защита (`try-catch`), программа **не упадет** с ошибкой,
         *         а переменная останется прежней (или не изменится), предотвращая сбои.
         */
        StreamSocket& operator>>(std::string& text);
        StreamSocket& operator>>(bool& value);
        StreamSocket& operator>>(char& value);
        StreamSocket& operator>>(int8_t& value);
        StreamSocket& operator>>(int16_t& value);
        StreamSocket& operator>>(int32_t& value);
        StreamSocket& operator>>(int64_t& value);
        StreamSocket& operator>>(uint8_t& value);
        StreamSocket& operator>>(uint16_t& value);
        StreamSocket& operator>>(uint32_t& value);
        StreamSocket& operator>>(uint64_t& value);
        StreamSocket& operator>>(float& value);
        StreamSocket& operator>>(double& value);
    };
}

#endif // _OTHER_SOCK_STREAM_H_
