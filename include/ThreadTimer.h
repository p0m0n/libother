#ifndef _OTHER_THREAD_TIMER_H_
#define _OTHER_THREAD_TIMER_H_

#include "Define.h"
#include "Timer.h"


namespace other::time::timer
{
    /**
     * @class ThreadTimer
     * @brief Потокобезопасный контроллер для управления таймерами.
     * Обеспечивает выполнение таймеров в отдельном фоновом потоке, защиту данных
     * через мьютексы и эффективное ожидание через condition_variable.
     */
    class ThreadTimer
    {
    private:
        mutable std::mutex      _mutex;      // Мьютекс для синхронизации доступа к данным родительского класса Timer
        std::shared_ptr<Timer>  _timer;      // Указатель на ядро логики таймеров
        std::condition_variable _cond_v;     // Используется для эффективного управления паузой и пробуждением потока
        std::thread             _thread;     // Фоновый рабочий поток
        std::atomic<bool>       _running;    // Атомарный флаг состояния жизненного цикла потока

    public:
        static ThreadTimer* Instance();

        /**
         * @brief Конструктор контроллера ThreadTimer.
         * Инициализирует контроллер, связывая его с объектом Timer.
         * По умолчанию контроллер создается в неактивном состоянии.
         * 
         * @param [in] parent: Общий указатель (shared_ptr) на экземпляр класса Timer.
         * 
         * Общее владение гарантирует, что ядро не будет удалено, пока жив контроллер.
         * Поток не запускается автоматически при создании объекта.
         * Для начала работы необходимо явно вызвать метод Start().
         */
        ThreadTimer(std::shared_ptr<Timer> timer = nullptr);
        /**
         * @brief Деструктор класса ThreadTimer.
         * Обеспечивает безопасное завершение фонового потока. Автоматически вызывает Stop(),
         * гарантируя, что поток будет остановлен и корректно присоединен (joined)
         * до того, как объект будет полностью удален из памяти.
         */
        virtual ~ThreadTimer();
        /**
         * @brief Проверяет, запущен ли фоновый поток обработки таймеров.
         * Позволяет узнать текущий статус активности контроллера ThreadTimer.
         * 
         * @return true, если метод Start() был успешно вызван и поток активен.
         * @return false, если метод Stop() был вызван или поток еще не запускался.
         * 
         * Этот метод проверяет состояние всего контроллера, а не конкретного таймера.
         */
        bool IsRunning() const;
        /**
         * @brief Инициализирует фоновый поток с заданной частотой проверки.
         * 
         * @param [in] sleepMilliseconds: Время максимального ожидания (сна) потока между проверками.
         * 
         * Чем меньше значение, тем выше точность таймеров, но выше нагрузка на CPU.
         * Значение 100мс является оптимальным балансом для большинства задач.
         */
        void Start(int sleepMilliseconds = 100);
        /**
         * @brief Безопасно останавливает фоновый поток.
         * 
         * 1. Устанавливает флаг завершения (_running = false).
         * 2. Будит фоновый поток, если тот находился в режиме ожидания.
         * 3. Дожидается полного завершения функции потока (join).
         * 
         * После вызова этого метода контроллер можно запустить снова методом Start().
         */
        void Stop();
        /**
         * @brief Создает новый таймер и регистрирует его в системе.
         * Таймер создается в состоянии ПАУЗЫ. Используйте StartTimer() или ResumeTimer() для запуска.
		 *
         * @param [in] startTime: Время активации (до этого момента таймер игнорируется).
         * @param [in] endTime:   Время первого срабатывания.
         * @param [in] callable:  Объект с логикой обратного вызова (колбэк).
         * @param [in] title:     Читаемое название для поиска и отладки (чувствительно к регистру).
		 *
         * @return Уникальный 64-битный идентификатор созданного таймера.
         */
        uint64_t CreateTimer(const DateTime& startTime, const DateTime& endTime, std::shared_ptr<ICallable> callable = nullptr, const std::string& title = "unknown");
        /**
         * @brief Активирует таймер (снимает с паузы).
         * Переводит таймер в рабочее состояние (_paused = false).
         * После вызова этого метода фоновый поток начнет отслеживать время и вызовет колбэк, как только наступит endTime.
         * 
         * @param [in] id: Уникальный идентификатор таймера, полученный при создании.
         * 
         * Если время срабатывания (endTime) уже прошло, пока таймер был
         * на паузе, он сработает мгновенно при следующей итерации потока.
         */
        void StartTimer(uint64_t id);
        /**
         * @brief Принудительно останавливает таймер и помечает его на удаление.
         * 
         * Устанавливает флаг _finish = true. После этого:
         * 1. Фоновый поток перестает вызывать колбэк этого таймера.
         * 2. Таймер будет физически удален из памяти при следующем вызове RemoveStopTimers().
         * 3. Попытки возобновить (Resume) этот таймер будут игнорироваться.
         * 
         * @param [in] id: Уникальный идентификатор таймера.
         */
        void StopTimer(uint64_t id);
        /**
         * @brief Временно приостанавливает отсчет времени для таймера.
         * Переводит таймер в состояние паузы (_paused = true).
         * 
         * Пока таймер на паузе:
         * 1. Фоновый поток игнорирует проверку его времени (CheckTimeout).
         * 2. Колбэк не будет вызван, даже если время endTime наступило.
         * 3. Таймер НЕ удаляется из памяти.
         * 
         * @param [in] id: Уникальный идентификатор таймера.
         */
        void PauseTimer(uint64_t id);
        /**
         * @brief Возобновляет работу ранее приостановленного таймера.
         * Снимает флаг паузы (_paused = false). Если время срабатывания таймера
         * наступило, пока он был на паузе, колбэк будет вызван при первой же проверке.
         * 
         * @param [in] id: Уникальный идентификатор таймера.
         */
        void ResumeTimer(uint64_t id);
        /**
         * @brief Перезапускает существующий таймер с новыми параметрами.
         * Позволяет изменить настройки времени и интервала для уже созданного таймера.
         * При перезапуске таймер автоматически СНИМАЕТСЯ с паузы и сбрасывает флаг завершения.
         * 
         * @param [in] id:        Уникальный идентификатор существующего таймера.
         * @param [in] startTime: Новое время активации.
         * @param [in] endTime:   Новое время ближайшего срабатывания.
         * 
         * Если таймер был завершен (_finish = true), этот метод вернет его к жизни.
         */
        void RestartTimer(uint64_t id, const DateTime& startTime, const DateTime& endTime);
        /**
         * @brief Возвращает время, прошедшее с момента активации таймера.
         * Расчет производится как разница между текущим моментом (Now) и начальной точкой отсчета (startTime).
         * 
         * @param [in] id: Уникальный идентификатор таймера.
         * 
         * @return TimeSpan, представляющий длительность работы таймера.
         * Если таймер еще не стал активным (Now < startTime), вернет TimeSpan::Zero.
         */
        TimeSpan ElapsedTime(uint64_t id) const;
        /**
         * @brief Возвращает время, оставшееся до ближайшего срабатывания таймера.
         * Расчет производится как разница между запланированным временем завершения (endTime) и текущим моментом (Now).
         * 
         * @param [in] id: Уникальный идентификатор таймера.
         * 
         * @return TimeSpan, представляющий время до срабатывания.
         * Если время уже вышло или таймер завершен, возвращает TimeSpan::Zero.
         * Для циклических таймеров это значение после срабатывания сбросится
         * и начнет отсчет заново до следующей итерации.
         */
        TimeSpan RemainingTime(uint64_t id) const;
        /**
         * @brief Ищет идентификатор таймера по его текстовому заголовку (названию).
         * Просматривает список всех зарегистрированных таймеров и возвращает ID первого
         * найденного таймера, чье поле _title совпадает с переданным параметром.
         * 
         * @param [in] title: Название таймера, указанное при его создании.
         * 
         * @return uint64_t Уникальный ID таймера. Если таймер с таким названием не найден, возвращает 0.
         * Поиск чувствителен к регистру (Case-sensitive).
         * Если есть несколько таймеров с одинаковыми именами, будет возвращен ID самого старого (созданного раньше).
         */
        uint64_t FindTimerIdFromTitle(const std::string& title) const;
        /**
         * @brief Очищает память от всех неактивных таймеров.
         * Метод проходит по списку и физически удаляет объекты, которые были помечены
         * флагом завершения (_finish = true) в результате работы CheckTimeout или вызова StopTimer().
         * 
         * @return uint64_t Количество удаленных из памяти объектов.
         * Рекомендуется вызывать этот метод периодически в основном потоке программы,
         * чтобы предотвратить бесконечный рост потребления оперативной памяти.
         */
        uint64_t RemoveStopTimers();
        /**
         * @brief Возвращает общее количество зарегистрированных в системе таймеров.
         * 
         * В это число входят:
         * 1. Активные работающие таймеры.
         * 2. Таймеры, поставленные на паузу.
         * 3. Завершенные таймеры, которые еще не были удалены методом RemoveStopTimers().
         * 
         * @return Общее количество объектов в контейнере.
         * Используется для мониторинга нагрузки и принятия решения о необходимости очистки памяти.
         */
        uint64_t TotalTimersCreated() const;
    };
}

#endif
