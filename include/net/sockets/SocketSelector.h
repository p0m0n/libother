#ifndef _OTHER_NET_SOCKETSELECTOR_H_
#define _OTHER_NET_SOCKETSELECTOR_H_

#include "Socket.h"


namespace other::net::sockets
{
    /**
     * @brief Кросс-платформенный мультиплексор сокетов на базе системных функций poll / WSAPoll.
     *
     * @details Позволяет реализовать неблокирующую асинхронную модель обработки сетевых
     * соединений (Reactor Pattern) в одном потоке. Вместо создания отдельного потока на каждого
     * клиента (thread-per-client), вы можете отслеживать тысячи сокетов одновременно, опрашивая
     * их состояние через единственный вызов Poll().
     */
    class SocketSelector
    {
    private:
        // Массив системных структур pollfd (дескриптор, маска запрашиваемых событий, маска результатов).
        // Передается напрямую в системный вызов poll / WSAPoll.
        std::vector<pollfd> _pollFds;

        // Параллельный массив указателей на исходные объекты Socket.
        // Служит для удобной связки системных дескрипторов с высокоуровневой логикой библиотеки.
        std::vector<const Socket*> _sockets;

    public:
        /**
         * @brief Конструктор по умолчанию. Создает пустой селектор.
         */
        SocketSelector() = default;
        /**
         * @brief Деструктор. Очищает внутренние списки отслеживания.
         */
        ~SocketSelector() = default;

        // Запрещаем копирование (селектор управляет уникальным набором системных дескрипторов)
        SocketSelector(const SocketSelector&) = delete;
        SocketSelector& operator=(const SocketSelector&) = delete;

        // Разрешаем безопасное перемещение объекта (move-only семантика)
        SocketSelector(SocketSelector&&) noexcept = default;
        SocketSelector& operator=(SocketSelector&&) noexcept = default;

        /**
         * @brief Добавляет сокет в набор для отслеживания.
         *
         * @param [in] socket: Ссылка на объект Socket, который необходимо контролировать.
         * @param [in] watchRead: Если true — отслеживать появление входящих данных (POLLIN) и закрытие соединения.
         * @param [in] watchWrite: Если true — отслеживать готовность буфера сокета к отправке данных (POLLOUT).
         */
        void Add(const Socket& socket, bool watchRead = true, bool watchWrite = false);
        /**
         * @brief Удаляет сокет из набора отслеживания.
         *
         * @param [in] socket: Ссылка на сокет, который больше не нужно контролировать.
         */
        void Remove(const Socket& socket);
        /**
         * @brief Полностью очищает весь набор отслеживаемых сокетов.
         */
        void Clear();
        /**
         * @brief Блокирующий опрос состояния всех добавленных сокетов (Event Loop).
         *
         * @details Функция ожидает, пока на каком-либо из сокетов не произойдет запрошенное событие
         * (например, пришли данные или сокет готов к отправке).
         *
         * @param [in] timeoutMs: Максимальное время ожидания в миллисекундах:
         *                         - Отрицательное (< 0) — ждать бесконечно, пока не случится событие.
         *                         - Нулевое (0) — мгновенный опрос (non-blocking проверка) и сразу возврат.
         *                         - Положительное (> 0) — ждать указанное число миллисекунд.
         *
         * @return int: Количество сокетов, у которых зафиксированы изменения (готовых к работе);
         *              0 — в случае истечения таймаута (ничего не произошло);
         *              -1 — в случае системной ошибки (детали можно узнать через GET_NET_ERROR()).
         */
        int Poll(int timeoutMs = -1);
        /**
         * @brief Проверяет, готов ли сокет к чтению (после выполнения метода Poll).
         *
         * @details Возвращает true, если:
         *          1. В буфере сокета есть входящие данные, готовые к чтению (recv).
         *          2. Удаленная сторона корректно закрыла соединение (сработал флаг POLLHUP).
         *          3. На сокете произошла системная ошибка приема (сработал флаг POLLERR).
         *
         * @param [in] socket: Проверяемый объект Socket.
         * @return true, если сокет доступен для чтения или требует обработки отключения/ошибки.
         */
        bool IsReadable(const Socket& socket) const;
        /**
         * @brief Проверяет, готов ли сокет к записи (после выполнения метода Poll).
         *
         * @details Возвращает true, если буфер отправки ОС свободен и можно отправлять данные (send),
         * либо если завершилось неблокирующее подключение (`connect`).
         *
         * @param [in] socket: Проверяемый объект Socket.
         * @return true, если сокет готов принимать данные для отправки.
         */
        bool IsWritable(const Socket& socket) const;
        /**
         * @brief Проверяет, произошла ли критическая ошибка на сокете (после выполнения Poll).
         *
         * @param [in] socket: Проверяемый объект Socket.
         * @return true, если сокет столкнулся с аппаратным сбросом (RST), разрывом связи или недействительным дескриптором.
         */
        bool HasError(const Socket & socket) const;
        /**
         * @brief Возвращает текущее количество сокетов, находящихся под наблюдением селектора.
         */
        size_t Size() const;
    };
}

#endif
